create table monitors (
    id uuid not null,
    owner_id uuid,
    expires_at timestamp(6) with time zone,
    name varchar(60) not null,
    url text not null,
    is_public boolean not null,
    enabled boolean not null,
    next_check_at timestamp(6) with time zone not null,
    last_status varchar(16),
    last_reason varchar(32),
    last_http_status integer,
    last_latency_ms integer,
    last_checked_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint pk_monitors primary key (id),
    constraint uq_monitors_owner_id unique (owner_id),
    constraint ck_monitors_last_status check (last_status in ('UP', 'DOWN', 'BLOCKED', 'REJECTED')),
    constraint ck_monitors_last_reason check (last_reason in (
        'SUCCESS', 'TIMEOUT', 'DNS_ERROR', 'CONNECTION_ERROR', 'TLS_ERROR', 'AUTH_REQUIRED', 'ACCESS_DENIED',
        'HTTP_4XX', 'HTTP_5XX', 'TOO_MANY_REDIRECTS', 'PRIVATE_ADDRESS', 'PORT_NOT_ALLOWED'
    ))
);

create index idx_monitors_next_check_at on monitors (next_check_at);
create index idx_monitors_expires_at on monitors (expires_at);
create index idx_monitors_is_public on monitors (is_public);

create table check_results (
    id bigint generated by default as identity,
    monitor_id uuid not null,
    checked_at timestamp(6) with time zone not null,
    status varchar(16) not null,
    reason varchar(32) not null,
    http_status integer not null,
    latency_ms integer not null,
    final_url text not null,
    redirects integer not null,
    constraint pk_check_results primary key (id),
    constraint fk_check_results_monitor foreign key (monitor_id) references monitors (id) on delete cascade,
    constraint ck_check_results_status check (status in ('UP', 'DOWN', 'BLOCKED', 'REJECTED')),
    constraint ck_check_results_reason check (reason in (
        'SUCCESS', 'TIMEOUT', 'DNS_ERROR', 'CONNECTION_ERROR', 'TLS_ERROR', 'AUTH_REQUIRED', 'ACCESS_DENIED',
        'HTTP_4XX', 'HTTP_5XX', 'TOO_MANY_REDIRECTS', 'PRIVATE_ADDRESS', 'PORT_NOT_ALLOWED'
    ))
);

create index idx_check_results_monitor_checked_at on check_results (monitor_id, checked_at desc);
create index idx_check_results_checked_at on check_results (checked_at);
